import 'split_tunnel_config.dart';

class PopularApp {
  final String id;
  final String name;
  final List<String> domains;
  final List<String> addresses;

  const PopularApp({
    required this.id,
    required this.name,
    required this.domains,
    this.addresses = const [],
  });

  String get iconAsset => 'assets/icons/apps/$id.svg';

  List<String> get ruleLabels => [
    for (final domain in domains) '${SplitTunnelRuleType.domain.name}:$domain',
    for (final address in addresses)
      '${SplitTunnelRuleType.geoip.name}:$address',
  ];
}

List<String> popularAppRules(Iterable<String> ids) {
  final selected = ids.toSet();
  return [
    for (final app in popularApps)
      if (selected.contains(app.id)) ...app.ruleLabels,
  ];
}

